"""Import the pinned GPL ChaosUhr bitmap data from a separately downloaded ZIP.

No network access and no execution of upstream code. Run from the project root:
python3 scripts/import_legacy_assets.py .pio/reference/chaosuhr-original.zip
"""
import hashlib
import json
from pathlib import Path
import re
import struct
import sys
from zipfile import ZipFile

COMMIT = "51aef401db22ef0fba3e5e334f141bf794d7505a"
FILES = ("DigiDug.h", "Qbert.h", "Face.h", "Face2.h", "Face3.h", "Feuer.h", "Drink.h", "BombJack.h")
UNUSED = {"Face006", "Face201"}
project = Path(__file__).resolve().parents[1]
archive_path = Path(sys.argv[1])
frames = []
manifest = {"repository": "https://github.com/oOmicha1986Oo/ChaosUhr", "commit": COMMIT, "files": {}, "frames": {}, "sequences": {}}
with ZipFile(archive_path) as archive:
    if archive.comment.decode() != COMMIT:
        raise SystemExit("Unexpected upstream revision; inspect before importing")
    prefix = archive.namelist()[0].split("/")[0] + "/"
    for filename in FILES:
        raw = archive.read(prefix+filename)
        manifest["files"][filename] = hashlib.sha256(raw).hexdigest()
        for name, body in re.findall(r"const long (\w+)\[\] PROGMEM\s*=\s*\{(.*?)\};", raw.decode(), re.S):
            if name in UNUSED:
                continue
            values = [int(value,16) for value in re.findall(r"0x([0-9a-fA-F]+)",body)]
            if len(values) != 300 or any(value > 0xffffff for value in values):
                raise SystemExit(f"Invalid 20x15 RGB888 frame: {name}")
            frames.append((name, values))
            packed = struct.pack("<300I",*values)
            manifest["frames"][name] = hashlib.sha256(packed).hexdigest()
    license_text = archive.read(prefix+"LICENSE")
    sketch = archive.read(prefix+"ChaosBlinkiBuntiUhr.ino").decode()
    manifest["files"]["ChaosBlinkiBuntiUhr.ino"] = hashlib.sha256(sketch.encode()).hexdigest()
    for effect, function in ((17,"DigiDug"),(18,"Qbert"),(19,"Face"),(20,"Face2"),(21,"Face3"),(22,"Fires"),(29,"Drink")):
        start = re.search(r"^void " + function + r"\(\)", sketch, re.M).start()
        body = re.split(r"\nvoid ",sketch[start:],maxsplit=1)[0]
        sequence = re.findall(r"pgm_read_dword\(&\((\w+)\[i\]\)\).*?delay\((\d+)\)",body,re.S)
        if not sequence:
            raise SystemExit(f"Missing source sequence: {function}")
        manifest["sequences"][str(effect)] = [{"frame":name,"ms":int(ms)} for name,ms in sequence]
    manifest["sequences"]["30"] = [{"frame":"BombJack01","ms":250},{"frame":"BombJack02","ms":250}]

lines = [
    "// SPDX-License-Identifier: GPL-3.0-only",
    "// Bitmap data by Micha1986 / oOmicha1986Oo, ChaosUhr.",
    f"// Source commit: {COMMIT}; see THIRD_PARTY.md.",
    "// Generated by scripts/import_legacy_assets.py; RGB888 and physical LED order preserved.",
    "#pragma once", "#include <stdint.h>", "namespace legacyAssets {",
]
for name, values in frames:
    lines.append(f"static const uint32_t {name}[300] PROGMEM = {{")
    for row in range(15):
        lines.append("  " + ",".join(f"0x{value:06x}" for value in values[row*20:(row+1)*20]) + ",")
    lines.append("};")
lines.append("} // namespace legacyAssets")
(project/"src"/"legacy_assets.h").write_text("\n".join(lines)+"\n")
(project/"tests"/"legacy_assets_manifest.json").write_text(json.dumps(manifest,indent=2)+"\n")
if not (project/"LICENSE").exists():
    (project/"LICENSE").write_bytes(license_text)
print(f"Imported {len(frames)} RGB888 frames ({len(frames)*300*4} bytes) from {COMMIT}")
