"""Deterministic ESP32-only assets. Decoded bytes must match source exactly."""
from pathlib import Path
import gzip,re,sys
root=Path(__file__).resolve().parents[1]
out=['// Generated by scripts/compress_esp32_web.py; do not edit.','#pragma once','#if defined(ESP32) && defined(ARDUINO)']
for name,path in [('INDEX_HTML','src/main.cpp'),('OTA_HTML','include/ota_ui.h'),('ERROR_JS','include/error_ui.h')]:
    source=(root/path).read_text()
    m=re.search(r'\b'+name+r'\[\].*?=R"(\w+)\((.*?)\)\1";',source,re.S)
    assert m,name
    # Compile the actual C++ initializer, including its conditional concatenation.
    import subprocess,tempfile
    declaration=m[0].split('=',1)[1]
    with tempfile.TemporaryDirectory() as d:
        cpp=Path(d)/'asset.cpp';exe=Path(d)/'asset'
        cpp.write_text('#include <cstdio>\n#define CHAOSUHR_PUBLIC_BUILD 1\nconst char asset[]='+declaration+'\nint main(){fwrite(asset,1,sizeof(asset)-1,stdout);}')
        subprocess.run(['g++',str(cpp),'-o',str(exe)],check=True)
        raw=subprocess.check_output([str(exe)])
    # ESP32-only clarification; Wemos HTML stays byte-identical.
    # Shared numbered version; no platform-specific replacement required.
    if name=='INDEX_HTML':
        raw=raw.replace('Animationsspeicher einrichten? Dabei werden vorhandene Dateien in diesem Speicher gelöscht. WLAN, Admin-Zugang und Uhreinstellungen bleiben erhalten.'.encode(),
          'LittleFS initialisieren? Alle Dateien dieser Partition werden gelöscht: eigene Animationen, MQTT-Konfiguration, zusätzliche Anzeigeeinstellungen und Speicherjournal. WLAN und Admin-Zugang im NVS bleiben erhalten. Bei beschädigter Installation zuerst sichern; nur bei bewusst akzeptiertem Datenverlust fortfahren.'.encode())
    data=gzip.compress(raw,compresslevel=9,mtime=0)
    assert gzip.decompress(data)==raw
    out.append('static const unsigned char '+name+'_GZ[] PROGMEM={'+','.join(map(str,data))+'};')
    print(name,len(raw),'->',len(data))
out += ['#define CLOCK_PAGE(server,type,name) do { (server).sendHeader("Content-Encoding","gzip"); (server).sendHeader("Vary","Accept-Encoding"); (server).send_P(200,type,reinterpret_cast<const char*>(name##_GZ),sizeof(name##_GZ)); } while(0)','#else','#define CLOCK_PAGE(server,type,name) (server).send_P(200,type,name)','#endif','']
path=root/'include/esp32_web_assets.h';result='\n'.join(out)
if '--check' in sys.argv:assert path.read_text()==result,'Stale gzip assets'
else:path.write_text(result)
